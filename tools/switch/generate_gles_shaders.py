#!/usr/bin/env python3
"""Generate the native Switch GLES 3 shaders from the shared model shaders."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "src/render/shaders/generated/model_gles3.h"


def convert(stage):
    source = (ROOT / f"src/render/shaders/model.{stage}").read_text()
    source = source.replace("#version 450", "#version 300 es\nprecision highp float;\nprecision highp int;\nprecision highp sampler2D;\nprecision highp samplerCube;", 1)
    source = re.sub(r"layout\(set = \d+, binding = \d+\) uniform (\w+) \{", r"layout(std140) uniform \1 {", source)
    source = re.sub(r"layout\(set = \d+, binding = \d+\) uniform sampler", "uniform sampler", source)
    # ES 3.0 supports locations on vertex inputs / fragment outputs, not varyings.
    direction = "out" if stage == "vert" else "in"
    source = re.sub(r"layout\(location = \d+\) " + direction + r"\b", direction, source)
    if stage == "vert":
        needle = "    gl_Position = u.mvp * vec4(a_pos, 1.0);"
        assert source.count(needle) == 1
        source = source.replace(needle, needle + "\n    // SDL_GPU depth [0,1] -> OpenGL clip depth [-1,1].\n    gl_Position.z = gl_Position.z * 2.0 - gl_Position.w;")
    assert "layout(set" not in source
    return source


def generated():
    result = "// Generated by tools/switch/generate_gles_shaders.py; edit the shared GLSL sources.\n#pragma once\n\nnamespace gt3r::render::shaders {\n"
    for stage in ("vert", "frag"):
        result += f'\ninline constexpr char model_{stage}_gles3[] = R"GLSL({convert(stage)})GLSL";\n'
    return result + "\n} // namespace gt3r::render::shaders\n"


if __name__ == "__main__":
    text = generated()
    if "--check" in sys.argv:
        if not DEST.exists() or DEST.read_text() != text:
            sys.exit("model_gles3.h is stale; run tools/switch/generate_gles_shaders.py")
    else:
        DEST.write_text(text)
